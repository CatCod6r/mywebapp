#!/bin/sh
set -e

echo "Запуск верифікації розгортання..."

# Оскільки скрипт виконується локально всередині ВМ через раннер,
# ми робимо запит безпосередньо на 80-й порт Nginx, який працює у ВМ
STATUS=$(curl -o /dev/null -s -w "%{http_code}" http://localhost:80/)

echo "Отримано статус-код: $STATUS"

if [ "$STATUS" = "200" ]; then
    echo "Верифікація успішна: веб-сервер повернув статус 200 OK!"
    exit 0
else
    echo "Верифікація провалена: отримано статус $STATUS"
    exit 1
fi
